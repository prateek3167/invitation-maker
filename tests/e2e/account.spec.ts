test('real HTTP authentication, cross-user isolation, CSRF and stale revision contracts', async ({ playwright }) => {
  const baseURL = 'http://127.0.0.1:3005';
  const alice = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { origin: baseURL } });
  const bob = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { origin: baseURL } });
  const guest = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { origin: baseURL } });
  try {
    expect((await guest.get('/api/v1/projects')).status()).toBe(401);
    expect((await guest.get('/api/v1/health')).status()).toBe(200);
    for (const [client, prefix] of [[alice, 'alice'], [bob, 'bob']] as const) {
      const email = `${prefix}-${Date.now()}@example.test`;
      const signup = await client.post('/api/auth/sign-up/email', { data: { name: prefix, email, password: 'A private test passphrase 123!' } });
      expect(signup.status(), await signup.text()).toBe(200);
      expect((await client.get('/api/v1/projects')).status()).toBe(401);
      await client.get(await mailLink(email));
    }
    const created = await alice.post('/api/v1/projects', { data: { title: 'Private celebration', occasion: 'Wedding', ownerId: 'not-the-owner' } });
    expect(created.status()).toBe(201); const { project } = await created.json();
    expect((await bob.get(`/api/v1/projects/${project.id}`)).status()).toBe(404);
    expect((await bob.patch(`/api/v1/projects/${project.id}`, { data: { title: 'Stolen', revision: 0 } })).status()).toBe(404);
    expect((await bob.delete(`/api/v1/projects/${project.id}`)).status()).toBe(404);
    const cardResponse = await alice.post(`/api/v1/projects/${project.id}/invitations`, { data: { templateId: '3' } });
    expect(cardResponse.status()).toBe(201); const { invitation } = await cardResponse.json();
    expect((await bob.get(`/api/v1/invitations/${invitation.id}`)).status()).toBe(404);
    expect((await bob.put(`/api/v1/invitations/${invitation.id}`, { data: { document: invitation } })).status()).toBe(404);
    expect((await bob.delete(`/api/v1/invitations/${invitation.id}`)).status()).toBe(404);
    expect((await alice.put(`/api/v1/invitations/${invitation.id}`, { data: { document: { ...invitation, font: 'modern' } } })).status()).toBe(200);
    const stale = await alice.put(`/api/v1/invitations/${invitation.id}`, { data: { document: invitation } });
    expect(stale.status()).toBe(409); expect((await stale.json()).error.code).toBe('CONFLICT');
    expect(stale.headers()['cache-control']).toBe('private, no-store'); expect(stale.headers()['x-request-id']).toBeTruthy();
    const csrf = await alice.post('/api/v1/projects', { headers: { origin: 'https://evil.example' }, data: { title: 'Forged', occasion: 'Wedding' } }); expect(csrf.status()).toBe(403);
    const signupCsrf = await guest.post('/api/auth/sign-up/email', { headers: { origin: 'https://evil.example' }, data: { name: 'Attack', email: 'attack@example.test', password: 'A private test passphrase 123!' } }); expect(signupCsrf.status()).toBe(403);
    const oversizedAuth = await guest.post('/api/auth/sign-up/email', { data: { name: 'x'.repeat(17000), email: 'large@example.test', password: 'A private test passphrase 123!' } }); expect(oversizedAuth.status()).toBe(413);
    expect((await alice.post('/api/v1/projects', { headers: { 'content-type': 'application/json' }, data: '{bad' })).status()).toBe(400);
    expect((await alice.get('/api/v1/projects/not-a-uuid')).status()).toBe(400);
    const anonymousCatalog = await guest.get('/api/v1/templates?photo=no&pageSize=50'); expect(anonymousCatalog.status()).toBe(200); expect((await anonymousCatalog.json()).total).toBe(23);
    expect((await alice.delete(`/api/v1/projects/${project.id}`)).status()).toBe(204);
    expect((await alice.get(`/api/v1/invitations/${invitation.id}`)).status()).toBe(404);
    await alice.post('/api/auth/sign-out', { data: {} }); expect((await alice.get('/api/v1/projects')).status()).toBe(401);
  } finally { await alice.dispose(); await bob.dispose(); await guest.dispose(); }
});
