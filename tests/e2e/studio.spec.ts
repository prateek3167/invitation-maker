test('photo upload, crop, persistence and image export', async ({ page }) => {
  await page.goto('/'); await page.getByLabel('Photo preference').selectOption('yes');
  await expect(page.locator('.template-card')).toHaveCount(57);
  await page.locator('.template-card').first().getByRole('button', { name: /Preview/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Make it yours', exact: true }).click();
  await page.getByRole('button', { name: 'Photo', exact: true }).click();
  const image = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 100; c.height = 100; const x = c.getContext('2d')!; x.fillStyle = '#ff8877'; x.fillRect(0, 0, 100, 100); return c.toDataURL().split(',')[1]; });
  await page.getByLabel('Upload invitation photo').setInputFiles({ name: 'test-photo.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
  await expect(page.getByLabel('Zoom', { exact: true })).toBeVisible();
  await page.getByLabel('Zoom', { exact: true }).fill('1.5');
  await page.getByLabel('Horizontal position').fill('25');
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Download', exact: true }).click();
  await page.getByLabel('File format').selectOption('jpg');
  const downloaded = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download JPG' }).click();
  expect((await downloaded).suggestedFilename()).toMatch(/\.jpg$/);
  await page.getByRole('button', { name: 'Back to studio' }).click();
  await page.getByRole('button', { name: /My projects/ }).click(); await page.locator('.project-art').first().click();
  await page.getByRole('button', { name: 'Photo', exact: true }).click();
  await expect(page.getByLabel('Zoom', { exact: true })).toHaveValue('1.5');
  await expect(page.getByLabel('Horizontal position')).toHaveValue('25');
});
