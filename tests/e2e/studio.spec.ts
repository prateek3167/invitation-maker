import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('discovery, complete draft recovery, actual exports and project lifecycle', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Big moments/ })).toBeVisible();
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  expect(accessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([]);
  await page.screenshot({ path: 'test-results/desktop-home.png', fullPage: false });
  await page.getByLabel('Photo preference').selectOption('no');
  await expect(page.locator('.template-card')).toHaveCount(23);
  await page.locator('.template-card').first().getByRole('button', { name: /Preview/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Make it yours', exact: true }).click();
  const editor = page.getByRole('dialog', { name: /Customize/ });
  await editor.getByLabel('First name / host').fill('Jamie');
  await editor.getByLabel('Second name / detail').fill('Alex');
  await editor.getByLabel('Draft name', { exact: true }).fill('Our September wedding');
  await editor.getByRole('button', { name: 'Design', exact: true }).click();
  await editor.getByRole('button', { name: 'Sage', exact: true }).click();
  await editor.getByLabel('Typography').selectOption('modern');
  await expect(editor.getByText('Saved on this device', { exact: true })).toBeVisible();
  const editorAccessibility = await new AxeBuilder({ page }).include('.editor-dialog').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  expect(editorAccessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([]);
  await page.screenshot({ path: 'test-results/desktop-editor.png', fullPage: false });
  await editor.getByRole('button', { name: 'Download', exact: true }).click();
  const downloadDialog = page.getByRole('dialog', { name: 'Ready for your big moment?' });
  const pngDownload = page.waitForEvent('download');
  await downloadDialog.getByRole('button', { name: 'Download PNG' }).click();
  const png = await pngDownload; expect(png.suggestedFilename()).toBe('Our September wedding.png');
  const pngStream = await png.createReadStream(); const pngChunks: Buffer[] = []; for await (const chunk of pngStream!) pngChunks.push(Buffer.from(chunk));
  const bytes = Buffer.concat(pngChunks); expect(bytes.readUInt32BE(16)).toBe(1500); expect(bytes.readUInt32BE(20)).toBe(2100);
  await editor.getByRole('button', { name: 'Download', exact: true }).click();
  await downloadDialog.getByLabel('File format').selectOption('pdf');
  const pdfDownload = page.waitForEvent('download'); await downloadDialog.getByRole('button', { name: 'Download PDF' }).click();
  const pdf = await pdfDownload; const pdfStream = await pdf.createReadStream(); const chunks: Buffer[] = []; for await (const chunk of pdfStream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks).subarray(0, 5).toString()).toBe('%PDF-');
  await editor.getByRole('button', { name: 'Back to studio' }).click();
  await page.getByRole('button', { name: /My projects/ }).click();
  await expect(page.getByRole('heading', { name: 'Our September wedding' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /My projects/ }).click();
  await page.getByRole('button', { name: 'Open Our September wedding' }).click();
  await expect(page.getByLabel('First name / host')).toHaveValue('Jamie');
  await page.getByRole('button', { name: 'Design', exact: true }).click();
  await expect(page.getByLabel('Typography')).toHaveValue('modern');
  await expect(page.getByRole('button', { name: 'Sage', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Back to studio' }).click();
  await page.getByRole('button', { name: 'Duplicate Our September wedding' }).click();
  await page.getByRole('button', { name: 'Back to studio' }).click();
  await expect(page.locator('.project-card')).toHaveCount(2);
  await page.getByRole('button', { name: 'Delete Our September wedding', exact: true }).click();
  await page.getByRole('button', { name: 'Delete draft', exact: true }).click();
  await expect(page.locator('.project-card')).toHaveCount(1);
  expect(errors).toEqual([]);
});

